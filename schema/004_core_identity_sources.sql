  last_name TEXT,
  birth_date TEXT,
  height INTEGER,
  weight INTEGER,
  college TEXT,
  gsis_id TEXT,
  espn_id TEXT,
  sportradar_id TEXT,
  yahoo_id TEXT,
  rotowire_id TEXT,
  pff_id TEXT,
  pfr_id TEXT,
  fantasy_data_id TEXT,
  sleeper_id TEXT,
  years_exp INTEGER,
  headshot_url TEXT,
  ngs_position TEXT,
  week INTEGER NOT NULL,
  game_type TEXT,
  status_description_abbr TEXT,
  football_name TEXT,
  esb_id TEXT,
  gsis_it_id TEXT,
  smart_id TEXT,
  entry_year INTEGER,
  rookie_year INTEGER,
  draft_club TEXT,
  draft_number INTEGER,
  load_id INTEGER NOT NULL REFERENCES load_log(load_id)
);

