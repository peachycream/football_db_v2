  pfr_id TEXT,
  cfbref_id TEXT,
  rotowire_id TEXT,
  rotoworld_id TEXT,
  ktc_id TEXT,
  stats_id TEXT,
  stats_global_id TEXT,
  fantasy_data_id TEXT,
  swish_id TEXT,
  name TEXT,
  merge_name TEXT,
  position TEXT,
  team TEXT,
  birthdate TEXT,
  age REAL,
  draft_year INTEGER,
  draft_round INTEGER,
  draft_pick INTEGER,
