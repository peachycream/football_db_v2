  display_name TEXT,
  common_first_name TEXT,
  first_name TEXT,
  last_name TEXT,
  short_name TEXT,
  football_name TEXT,
  suffix TEXT,
  esb_id TEXT,
  nfl_id TEXT,
  pfr_id TEXT,
  pff_id TEXT,
  otc_id TEXT,
  espn_id TEXT,
  smart_id TEXT,
  birth_date TEXT,
  position_group TEXT,
  position TEXT,
  ngs_position_group TEXT,
  ngs_position TEXT,
  height INTEGER,
  weight INTEGER,
  headshot TEXT,
  college_name TEXT,
  college_conference TEXT,
  jersey_number INTEGER,
  rookie_season INTEGER,
  last_season INTEGER,
  latest_team TEXT,
  status TEXT,
  ngs_status TEXT,
  ngs_status_short_description TEXT,
  years_of_experience INTEGER,
  pff_position TEXT,
  pff_status TEXT,
  draft_year INTEGER,
  draft_round INTEGER,
  draft_pick INTEGER,
  draft_team TEXT,
  load_id INTEGER NOT NULL REFERENCES load_log(load_id)
);

-- nflverse weekly rosters (release assets weekly_rosters/roster_weekly_<season>.csv), 2016-.
